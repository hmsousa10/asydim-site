(function initCarousel() {
    const track = document.getElementById("carousel-track");
    const slides = track ? [ ...track.querySelectorAll(".carousel-slide") ] : [];
    if (!slides.length) return;
    track.dataset.currentIdx = "0";
    const tagEl = document.getElementById("car-tag");
    const titleEl = document.getElementById("car-title");
    const countEl = document.getElementById("car-count");
    const dots = [ ...document.querySelectorAll(".car-dot") ];
    const total = slides.length;
    let current = 0;
    let autoTimer;
    let userPaused = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const pauseButton = document.getElementById("carousel-toggle");
    function updatePauseButton() {
        if (!pauseButton) return;
        pauseButton.dataset.i18n = userPaused ? "proj.play" : "proj.pause";
        pauseButton.textContent = t(pauseButton.dataset.i18n);
        pauseButton.setAttribute("aria-pressed", String(userPaused));
    }
    updatePauseButton();
    let isAnimating = false;
    function goTo(idx) {
        if (isAnimating) return;
        isAnimating = true;
        current = (idx + total) % total;
        track.dataset.currentIdx = String(current);
        document.dispatchEvent(new CustomEvent("asydim:projectchange"));
        track.style.transform = `translateX(-${current * 100}%)`;
        [ tagEl, titleEl ].forEach(el => {
            if (el) el.style.opacity = "0";
        });
        setTimeout(() => {
            const sl = slides[current];
            if (tagEl) tagEl.textContent = sl.dataset.i18nTag ? t(sl.dataset.i18nTag) : sl.dataset.tag || "";
            if (titleEl) titleEl.textContent = sl.dataset.i18nTitle ? t(sl.dataset.i18nTitle) : sl.dataset.title || "";
            [ tagEl, titleEl ].forEach(el => {
                if (el) el.style.opacity = "1";
            });
        }, 220);
        dots.forEach((d, i) => {
            d.classList.toggle("active", i === current);
            d.setAttribute("aria-current", String(i === current));
        });
        setTimeout(() => {
            isAnimating = false;
        }, 500);
    }
    document.getElementById("car-prev")?.addEventListener("click", () => {
        goTo(current - 1);
        resetAuto();
    });
    document.getElementById("car-next")?.addEventListener("click", () => {
        goTo(current + 1);
        resetAuto();
    });
    dots.forEach(d => d.addEventListener("click", () => {
        goTo(+d.dataset.idx);
        resetAuto();
    }));
    document.getElementById("proj-carousel")?.addEventListener("keydown", e => {
        if (e.key === "ArrowLeft" || e.key === "ArrowRight") e.preventDefault();
        if (e.key === "ArrowLeft") {
            goTo(current - 1);
            resetAuto();
        }
        if (e.key === "ArrowRight") {
            goTo(current + 1);
            resetAuto();
        }
    });
    let touchStartX = 0;
    let touchEndX = 0;
    let isDragging = false;
    function handleDragStart(x) {
        touchStartX = x;
        isDragging = true;
        clearInterval(autoTimer);
    }
    function handleDragEnd(x) {
        if (!isDragging) return;
        isDragging = false;
        touchEndX = x;
        const swipeThreshold = 40;
        if (touchEndX < touchStartX - swipeThreshold) goTo(current + 1); else if (touchEndX > touchStartX + swipeThreshold) goTo(current - 1);
        resetAuto();
    }
    track.addEventListener("touchstart", e => handleDragStart(e.changedTouches[0].screenX), {
        passive: true
    });
    track.addEventListener("touchend", e => handleDragEnd(e.changedTouches[0].screenX), {
        passive: true
    });
    track.addEventListener("mousedown", e => {
        e.preventDefault();
        handleDragStart(e.screenX);
    });
    track.addEventListener("mouseup", e => handleDragEnd(e.screenX));
    track.addEventListener("mouseleave", e => handleDragEnd(e.screenX));
    function startAuto() {
        clearInterval(autoTimer);
        if (userPaused || document.hidden || carousel?.contains(document.activeElement)) return;
        autoTimer = setInterval(() => goTo(current + 1), 6e3);
    }
    function resetAuto() {
        clearInterval(autoTimer);
        startAuto();
    }
    const carousel = document.getElementById("proj-carousel");
    carousel?.addEventListener("mouseenter", () => clearInterval(autoTimer));
    carousel?.addEventListener("mouseleave", startAuto);
    carousel?.addEventListener("focusin", () => clearInterval(autoTimer));
    carousel?.addEventListener("focusout", () => setTimeout(startAuto, 0));
    document.addEventListener("visibilitychange", () => document.hidden ? clearInterval(autoTimer) : startAuto());
    pauseButton?.addEventListener("click", () => {
        userPaused = !userPaused;
        updatePauseButton();
        userPaused ? clearInterval(autoTimer) : startAuto();
    });
    [ tagEl, titleEl, countEl ].forEach(el => {
        if (el) el.style.transition = "opacity .25s ease";
    });
    startAuto();
})();

