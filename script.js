function openDrawer() {
    if (!mobileDrawer || !mobileNavigation.matches || mobileDrawer.classList.contains("open")) return;
    drawerReturnFocus = document.activeElement;
    drawerScrollY = window.scrollY;
    mobileDrawer.inert = false;
    mobileDrawer.classList.add("open");
    backdrop?.classList.add("open");
    hamburger?.classList.add("open");
    hamburger?.setAttribute("aria-expanded", "true");
    hamburger?.setAttribute("aria-label", t("nav.closeMenu"));
    mobileDrawer.setAttribute("aria-hidden", "false");
    document.body.classList.add("drawer-open");
    document.body.style.top = `-${drawerScrollY}px`;
    drawerClose?.focus({
        preventScroll: true
    });
    [ ...document.body.children ].forEach(el => {
        if (el === mobileDrawer || el === backdrop || el.tagName === "SCRIPT") return;
        drawerBackground.set(el, el.inert);
        el.inert = true;
    });
}

function closeDrawer() {
    if (!mobileDrawer?.classList.contains("open")) return;
    mobileDrawer.classList.remove("open");
    backdrop?.classList.remove("open");
    hamburger?.classList.remove("open");
    hamburger?.setAttribute("aria-expanded", "false");
    hamburger?.setAttribute("aria-label", t("nav.openMenu"));
    drawerBackground.forEach((inert, el) => {
        el.inert = inert;
    });
    drawerBackground.clear();
    document.body.classList.remove("drawer-open");
    document.body.style.top = "";
    window.scrollTo({
        top: drawerScrollY,
        behavior: "instant"
    });
    if (drawerReturnFocus?.getClientRects().length) drawerReturnFocus.focus({
        preventScroll: true
    });
    mobileDrawer.inert = true;
    mobileDrawer.setAttribute("aria-hidden", "true");
}

