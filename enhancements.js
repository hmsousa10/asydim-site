function formatEuro(value) {
    return new Intl.NumberFormat(document.documentElement.lang === "en" ? "en-GB" : "pt-PT", {
        style: "currency",
        currency: "EUR",
        maximumFractionDigits: 0
    }).format(value);
}

function updateEnergyCalculator() {
    const slider = document.getElementById("monthly-bill");
    if (!slider) return;
    const bill = Number(slider.value);
    document.getElementById("monthly-bill-value").textContent = formatEuro(bill);
    document.getElementById("optimised-bill").textContent = formatEuro(Math.round(bill * .68));
    document.getElementById("annual-saving").textContent = formatEuro(Math.round(bill * .32 * 12));
    slider.setAttribute("aria-valuetext", formatEuro(bill));
    slider.style.setProperty("--range-progress", `${(bill - 500) / 49500 * 100}%`);
    document.getElementById("calculator-cta").href = `index.html?assunto=procurement&fatura=${bill}#contacto`;
}

